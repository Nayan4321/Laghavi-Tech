-- Transara service tables (MySQL 5.7+ / MariaDB 10.3+).
CREATE TABLE IF NOT EXISTS sites (
	id INT UNSIGNED NOT NULL AUTO_INCREMENT,
	site_url VARCHAR(255) NOT NULL,
	license_enc TEXT NOT NULL,
	token_hash CHAR(64) NOT NULL,
	status VARCHAR(20) NOT NULL DEFAULT 'active',
	license_status VARCHAR(20) NOT NULL DEFAULT 'active',
	license_checked INT UNSIGNED NOT NULL DEFAULT 0,
	slug VARCHAR(80) NULL,
	custom_domain VARCHAR(190) NULL,
	settings MEDIUMTEXT NULL,
	created INT UNSIGNED NOT NULL DEFAULT 0,
	last_seen INT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (id),
	UNIQUE KEY site_url (site_url),
	UNIQUE KEY token_hash (token_hash),
	UNIQUE KEY slug (slug),
	UNIQUE KEY custom_domain (custom_domain)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS monitors (
	id INT UNSIGNED NOT NULL AUTO_INCREMENT,
	site_id INT UNSIGNED NOT NULL,
	ext_id VARCHAR(40) NOT NULL,
	name VARCHAR(190) NOT NULL DEFAULT '',
	type VARCHAR(20) NOT NULL DEFAULT 'http',
	target VARCHAR(500) NOT NULL DEFAULT '',
	options TEXT NULL,
	interval_sec INT UNSIGNED NOT NULL DEFAULT 60,
	retries TINYINT UNSIGNED NOT NULL DEFAULT 2,
	public TINYINT(1) NOT NULL DEFAULT 0,
	paused TINYINT(1) NOT NULL DEFAULT 0,
	status VARCHAR(10) NOT NULL DEFAULT 'pending',
	fails SMALLINT UNSIGNED NOT NULL DEFAULT 0,
	last_check INT UNSIGNED NOT NULL DEFAULT 0,
	last_change INT UNSIGNED NOT NULL DEFAULT 0,
	last_ms INT UNSIGNED NOT NULL DEFAULT 0,
	last_message VARCHAR(255) NOT NULL DEFAULT '',
	hb_token CHAR(32) NULL,
	hb_last INT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (id),
	UNIQUE KEY site_ext (site_id, ext_id),
	UNIQUE KEY hb_token (hb_token),
	KEY due (paused, last_check)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS checks (
	id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	monitor_id INT UNSIGNED NOT NULL,
	region VARCHAR(40) NOT NULL DEFAULT '',
	time INT UNSIGNED NOT NULL,
	ok TINYINT(1) NOT NULL DEFAULT 0,
	code INT NOT NULL DEFAULT 0,
	ms INT UNSIGNED NOT NULL DEFAULT 0,
	message VARCHAR(255) NOT NULL DEFAULT '',
	PRIMARY KEY (id),
	KEY monitor_time (monitor_id, time)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS incidents (
	id INT UNSIGNED NOT NULL AUTO_INCREMENT,
	monitor_id INT UNSIGNED NOT NULL,
	started INT UNSIGNED NOT NULL,
	ended INT UNSIGNED NOT NULL DEFAULT 0,
	cause VARCHAR(255) NOT NULL DEFAULT '',
	regions VARCHAR(255) NOT NULL DEFAULT '',
	acked INT UNSIGNED NOT NULL DEFAULT 0,
	escalated INT UNSIGNED NOT NULL DEFAULT 0,
	note TEXT NULL,
	PRIMARY KEY (id),
	KEY monitor_started (monitor_id, started)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS subscribers (
	id INT UNSIGNED NOT NULL AUTO_INCREMENT,
	site_id INT UNSIGNED NOT NULL,
	email VARCHAR(190) NOT NULL,
	confirmed TINYINT(1) NOT NULL DEFAULT 0,
	created INT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (id),
	UNIQUE KEY site_email (site_id, email)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS alerts_log (
	id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	site_id INT UNSIGNED NOT NULL,
	time INT UNSIGNED NOT NULL,
	channel VARCHAR(20) NOT NULL,
	ok TINYINT(1) NOT NULL DEFAULT 0,
	detail VARCHAR(255) NOT NULL DEFAULT '',
	PRIMARY KEY (id),
	KEY site_time (site_id, time)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rate_limits (
	bucket VARCHAR(190) NOT NULL,
	hits INT UNSIGNED NOT NULL DEFAULT 0,
	PRIMARY KEY (bucket)
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS meta (
	name VARCHAR(80) NOT NULL,
	value TEXT NULL,
	PRIMARY KEY (name)
) DEFAULT CHARSET=utf8mb4;
